#!/usr/bin/env python3
"""Build ONE paste-and-run SQL file that rebuilds the whole Yantrika schema.

    python scripts/build_full_schema.py [out.sql]
    default out: supabase/oneshot/full-schema.sql   (git-ignored)

The file is a single transaction:

  1. WIPE - drops exactly the tables, functions and the auth.users trigger that
     the migrations define (names are parsed from supabase/*.sql, so it can
     never touch anything else in the project). ALL ROWS IN THOSE TABLES ARE
     LOST. Use it only on a project with no data you need.
  2. REBUILD - every migration in order, 0001-0005 then 0007-0019. 0006 is
     skipped on purpose: 0007 (RBAC) supersedes it and removes its policies.
     The wipe makes the intermediate "demo-open" state of 0001 irrelevant: it
     is inside one transaction and 0007 closes it before commit.

The finished project is locked down: anonymous visitors can read and write
nothing except what 0009/0019 deliberately allow (a throwaway DEMO-* sandbox
site; a workspace's own rows with its ingest key).
"""
from __future__ import annotations

import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
MIG = ROOT / "supabase"
SKIP = {"0006_harden.sql"}


def migrations() -> list[Path]:
    return sorted(p for p in MIG.glob("[0-9][0-9][0-9][0-9]_*.sql") if p.name not in SKIP)


def parse_objects(files: list[Path]):
    text = "\n".join(p.read_text(encoding="utf-8") for p in files)
    # ignore commented-out ROLLBACK blocks
    code = "\n".join(l for l in text.splitlines() if not l.lstrip().startswith("--"))
    tables = sorted(set(re.findall(
        r"create\s+table\s+(?:if\s+not\s+exists\s+)?public\.([a-z_][a-z0-9_]*)", code, re.I)))
    funcs = sorted(set(re.findall(
        r"create\s+(?:or\s+replace\s+)?function\s+public\.([a-z_][a-z0-9_]*)", code, re.I)))
    triggers = sorted(set(re.findall(
        r"create\s+trigger\s+([a-z_][a-z0-9_]*)[^;]*?\bon\s+auth\.users", code, re.I | re.S)))
    types = sorted(set(re.findall(r"create\s+type\s+public\.([a-z_][a-z0-9_]*)", code, re.I)))
    return tables, funcs, triggers, types


def build() -> str:
    files = migrations()
    tables, funcs, triggers, types = parse_objects(files)
    q = lambda xs: ", ".join("'" + x + "'" for x in xs)
    out = [
        "-- ============================================================================",
        "-- Yantrika FULL SCHEMA REBUILD (generated by scripts/build_full_schema.py)",
        "--",
        "-- !! DESTRUCTIVE !!  Drops and recreates every Yantrika table, function and",
        "-- the auth.users trigger. Every row in those tables is deleted. Auth users",
        "-- (auth.users) are NOT touched. Paste into Supabase > SQL Editor > Run.",
        "-- One transaction: if anything fails, nothing changes.",
        f"-- Migrations included, in order: {', '.join(p.name[:4] for p in files)}",
        "-- ============================================================================",
        "begin;",
        "",
        "-- ---- 1) WIPE (only objects defined by the migrations) ------------------------",
    ]
    for t in triggers:
        out.append(f"drop trigger if exists {t} on auth.users;")
    out += [
        "do $wipe$",
        "declare r record;",
        "begin",
        f"  for r in select p.oid::regprocedure as sig from pg_proc p",
        f"           join pg_namespace n on n.oid = p.pronamespace",
        f"           where n.nspname = 'public' and p.proname in ({q(funcs)}) loop",
        "    execute 'drop function if exists ' || r.sig || ' cascade';",
        "  end loop;",
        f"  for r in select unnest(array[{q(tables)}]) as t loop",
        "    execute format('drop table if exists public.%I cascade', r.t);",
        "  end loop;",
    ]
    for ty in types:
        out.append(f"  execute 'drop type if exists public.{ty} cascade';")
    out += ["end", "$wipe$;", ""]
    for p in files:
        out += [f"-- ---- {p.name} " + "-" * max(4, 60 - len(p.name)), p.read_text(encoding="utf-8").rstrip(), ""]
    out += [
        "-- ---- make the REST API see the new schema -----------------------------------",
        "notify pgrst, 'reload schema';",
        "commit;",
        "",
    ]
    return "\n".join(out)


if __name__ == "__main__":
    dest = Path(sys.argv[1]) if len(sys.argv) > 1 else MIG / "oneshot" / "full-schema.sql"
    dest.parent.mkdir(parents=True, exist_ok=True)
    dest.write_text(build(), encoding="utf-8")
    t, f, tr, ty = parse_objects(migrations())
    print(f"wrote {dest} ({dest.stat().st_size // 1024} KB): wipes {len(t)} tables, "
          f"{len(f)} functions, {len(tr)} auth trigger(s), {len(ty)} type(s)")
